#!/usr/bin/env python3
"""Embed the repo's config files into docker-compose.yaml as inline `configs:`.

Coolify does not copy repository files for Git-based Compose deploys, so a
bind mount like ./nginx/nginx.conf.template arrives as an empty directory.
Inline configs travel inside the compose file itself.

Run after editing any file listed in CONFIGS:  python3 scripts/embed-configs.py
Check without writing (exit 1 when stale):     python3 scripts/embed-configs.py --check
"""

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
COMPOSE = ROOT / "docker-compose.yaml"
BEGIN = "# BEGIN embedded configs (generated by scripts/embed-configs.py, do not edit)"
END = "# END embedded configs"

CONFIGS = {
    "nginx_conf": "nginx/nginx.conf.template",
    "nginx_proxy_conf": "nginx/proxy.conf.template",
    "nginx_https_conf": "nginx/https.conf.template",
    "nginx_default_conf": "nginx/conf.d/default.conf.template",
    "nginx_entrypoint": "nginx/docker-entrypoint.sh",
    "squid_conf": "ssrf_proxy/squid.conf.template",
    "squid_common_conf": "ssrf_proxy/squid-common.conf.template",
    "squid_agent_conf": "ssrf_proxy/squid-agent.conf.template",
    "ssrf_entrypoint": "ssrf_proxy/docker-entrypoint.sh",
    "ssrf_agent_entrypoint": "ssrf_proxy/docker-agent-entrypoint.sh",
    "sandbox_config": "volumes/sandbox/conf/config.yaml",
    "postgres_initdb_plugin": "postgres/initdb/01-create-plugin-db.sh",
}


def render() -> str:
    lines = [BEGIN, "configs:"]
    for name, rel in CONFIGS.items():
        text = (ROOT / rel).read_text()
        if not text.endswith("\n"):
            text += "\n"
        lines.append(f"  {name}:  # {rel}")
        lines.append("    content: |")
        for line in text.splitlines():
            # Compose interpolates ${...} in content; the templates expect envsubst in the container.
            escaped = line.replace("$", "$$")
            lines.append(f"      {escaped}" if escaped else "")
    lines.append(END)
    return "\n".join(lines) + "\n"


def main() -> int:
    compose = COMPOSE.read_text()
    block = render()
    if BEGIN in compose:
        head, rest = compose.split(BEGIN, 1)
        if END not in rest:
            sys.exit(f"{COMPOSE.name}: found '{BEGIN}' without '{END}'")
        tail = rest.split(END, 1)[1].lstrip("\n")
        updated = head + block + tail
    else:
        updated = compose.rstrip("\n") + "\n\n" + block
    if "--check" in sys.argv:
        if updated != compose:
            print("embedded configs are stale; run python3 scripts/embed-configs.py", file=sys.stderr)
            return 1
        print("embedded configs are up to date")
        return 0
    COMPOSE.write_text(updated)
    print(f"embedded {len(CONFIGS)} configs into {COMPOSE.name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
